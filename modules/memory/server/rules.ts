/**
 * Standing rules: memories of kind `rule` (design: docs/cortex standing-rules
 * input, sections 7 and 8; 19 and 20 Oct 2026).
 *
 * A rule is a guideline WITH ITS REASON, not a blind command: the model reads
 * the why and judges whether the case is the one the rule is for. Each rule
 * names its scope, so the always-on list stays short: only user-wide rules
 * that apply whenever ("when: always") are rendered into rules.md, which the
 * user's CLAUDE.md imports. Everything scoped waits for its trigger.
 *
 * Front matter is flat `key: value` lines, so a person can write one by hand:
 *
 *   kind: rule
 *   category: code
 *   why: a TODO left in shipped code is a promise nobody tracks
 *   source: [[feedback-no-todo-in-shipped-code]]
 *   scope: user                  user | role:<role> | repo:<name> | project:<glob> | client:<name> | counterparty:<name>
 *   valid: always                always | until: <condition> | while: <condition>
 *   review_by: 2026-12-01        optional, with until/while
 *   when: path:src/**            always | text_for:<targets> | path:<glob> | cwd:<glob> | tool:<name> | keywords:<a,b>
 *   do: no TODO comments; open an issue and link it instead
 *   check: regex:\bTODO\b  regex:<pattern> | manual
 *   enforce: audit               none | remind | audit | deny
 */

import fs from 'node:fs'
import path from 'node:path'

export const ENFORCE = ['none', 'remind', 'audit', 'deny'] as const
export type Enforce = (typeof ENFORCE)[number]

export type Rule = {
  id: string
  name: string
  category: string
  why: string
  source: string[]
  scope: string
  valid: string
  reviewBy?: string
  when: string
  do: string
  check: string
  enforce: Enforce
  /** When the rule was written: a correction before it cannot be about it. */
  since?: number
}

export type RuleFields = Omit<Rule, 'id' | 'name' | 'since'>

const FIELDS = ['kind', 'category', 'why', 'source', 'scope', 'valid', 'review_by', 'when', 'do', 'check', 'enforce'] as const

const unquote = (v: string): string => v.trim().replace(/^(['"])(.*)\1$/, '$2').trim()

/** The rule fields of a memory's front matter, or null when it is not `kind: rule`. */
export const ruleOf = (content: string): RuleFields | null => {
  const m = content.match(/^\s*---\s*\n([\s\S]*?)\n---/)
  if (!m) return null
  // Top level, or nested: the harness normaliser can move keys under `metadata:` (as frontmatter.ts
  // reads `type`), and a rule written that way was ingested as a plain observation. Top level wins.
  const top: Record<string, string> = {}
  const nested: Record<string, string> = {}
  for (const line of (m[1] ?? '').split('\n')) {
    const kv = line.match(/^(\s*)([a-z_]+):\s*(.*)$/)
    if (kv && (FIELDS as readonly string[]).includes(kv[2]!)) (kv[1] ? nested : top)[kv[2]!] = unquote(kv[3]!.replace(/\s+#\s.*$/, ''))
  }
  const f: Record<string, string> = { ...nested, ...top }
  if (f.kind?.toLowerCase() !== 'rule') return null
  const enforce = (ENFORCE as readonly string[]).includes(f.enforce ?? '') ? (f.enforce as Enforce) : 'remind'
  return {
    category: f.category || 'general',
    why: f.why ?? '',
    source: [...(f.source ?? '').matchAll(/\[\[([^\]]+)\]\]/g)].map((x) => x[1]!.trim()),
    scope: f.scope || 'user',
    valid: f.valid || 'always',
    ...(f.review_by ? { reviewBy: f.review_by } : {}),
    when: f.when || 'always',
    do: f.do ?? '',
    check: f.check || 'manual',
    enforce,
  }
}

/** Rules that belong in the always-on rules.md: user-wide or role lines, applying whenever. */
export const alwaysOn = (rules: Rule[]): Rule[] =>
  rules.filter((r) => r.when === 'always' && (r.scope === 'user' || r.scope.startsWith('role:')) && r.valid === 'always')

const CATEGORY_TITLE = (c: string) => c.replace(/[-_]+/g, ' ').replace(/^./, (x) => x.toUpperCase())

/** One line per rule: what to do, then the reason in a few words. */
export const ruleLine = (r: Rule): string => `- ${r.do || r.name}${r.why ? ` (${r.why})` : ''}`

export const RULES_HEADING = '## Cortex: standing rules (guidelines with reasons; full text: cortex-rules show <name>)'

/**
 * rules.md, grouped by category; role lines under their role. Always some text,
 * never an empty file: a missing or empty import is skipped silently by the
 * harness (E1, 20 Oct), so an empty file would look the same as a broken one.
 */
export const renderRulesMd = (rules: Rule[]): string => {
  const on = alwaysOn(rules).sort((a, b) => a.category.localeCompare(b.category) || a.name.localeCompare(b.name))
  const out = ['<!-- Generated by Cortex from rule memories; edit the memory, not this file. -->', RULES_HEADING]
  if (!on.length) return [...out, '', '(No always-on rules yet.)', ''].join('\n')
  const users = on.filter((r) => r.scope === 'user')
  for (const cat of [...new Set(users.map((r) => r.category))]) {
    out.push('', `### ${CATEGORY_TITLE(cat)}`, ...users.filter((r) => r.category === cat).map(ruleLine))
  }
  const roles = on.filter((r) => r.scope.startsWith('role:'))
  for (const role of [...new Set(roles.map((r) => r.scope.slice(5)))]) {
    out.push('', `### If this session is in role ${role}`, ...roles.filter((r) => r.scope === `role:${role}`).map(ruleLine))
  }
  return [...out, ''].join('\n')
}

// ── checking text ────────────────────────────────────────────────────────────

/**
 * Quoted text and code are exempt: a quote is reproduced exactly, never
 * cleaned up (19 Oct 2026), and code is not prose. Quotes are lines starting
 * with ">" and text inside straight or curly double quotes; code is fenced
 * blocks and inline code spans.
 */
export const maskExempt = (text: string): string => {
  const blank = (s: string) => s.replace(/[^\n]/g, ' ')
  return text
    .replace(/```[\s\S]*?```/g, blank)
    .split('\n')
    .map((line) =>
      line.trimStart().startsWith('>') ? blank(line) : line.replace(/"[^"\n]*"|“[^”\n]*”|`[^`\n]*`/g, blank),
    )
    .join('\n')
}

export type Violation = { rule: string; line: number; col: number; excerpt: string }

const regexOf = (check: string): RegExp | null => {
  if (!check.startsWith('regex:')) return null
  try {
    return new RegExp(check.slice(6), 'g')
  } catch {
    return null
  }
}

/** Every checkable rule against the text, outside quotes and code. */
export const checkText = (text: string, rules: Rule[]): Violation[] => {
  const masked = maskExempt(text).split('\n')
  const lines = text.split('\n')
  const out: Violation[] = []
  for (const r of rules) {
    const re = regexOf(r.check)
    if (!re) continue
    masked.forEach((line, i) => {
      for (const m of line.matchAll(re)) out.push({ rule: r.name, line: i + 1, col: (m.index ?? 0) + 1, excerpt: (lines[i] ?? '').trim().slice(0, 80) })
    })
  }
  return out
}

/** Rules that apply to text for others (when: text_for:...), the ones an outbound check runs. */
export const forOutbound = (rules: Rule[]): Rule[] => rules.filter((r) => r.when.startsWith('text_for:') || r.when === 'always')

/**
 * An external target named in a prompt: Slack, WhatsApp, email, a doc for
 * others, "for <Name>". Only names it; deciding whether text is external stays
 * the model's call (section 8).
 */
export const namedTarget = (prompt: string): string | undefined => {
  const m = prompt.match(/\b(slack|whatsapp|e-?mail|linkedin|text message|sms)\b/i)
  if (m) return m[1]!.toLowerCase().replace('e-mail', 'email')
  if (/\b(message|note|reply|letter|draft)\s+(?:to|for)\s+[A-Z][a-z]+/.test(prompt)) return 'person'
  return undefined
}

/** Write rules.md when its text changes; returns whether it did. */
export const writeRulesMd = (file: string, rules: Rule[]): boolean => {
  const text = renderRulesMd(rules)
  let now = ''
  try {
    now = fs.readFileSync(file, 'utf-8')
  } catch {
    /* not written yet */
  }
  if (now === text) return false
  fs.mkdirSync(path.dirname(file), { recursive: true })
  fs.writeFileSync(file, text, 'utf-8')
  return true
}
